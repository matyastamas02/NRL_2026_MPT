"""A hierarchical Bayesian translation, sampled from scratch (Gibbs).

    y_i = a_d + b_d (x_i - m) + e_i,   e_i ~ N(0, s2_d)
    (a_d, b_d) ~ N((A, B), diag(ta2, tb2))        partial pooling across directions
    s2_d ~ InvGamma(nu/2, nu s2_0 / 2)            pooled noise, s2_0 the pooled variance
    A, B flat; ta2, tb2 ~ InvGamma(1, 1)          weak
d is the direction, x the source rating, m the mean source rating of the training
pairs. Every conditional is conjugate, so the sampler is plain Gibbs. A direction with
no training pairs takes (a, b) from the population (A, B, ta2, tb2).

What it gives that the app's line does not is a full predictive distribution per
player: a mean, any range, and P(top third) as the share of predictive draws above the
target competition's top-third threshold (taken from the last season known). Scored
rolling, each landing season from the pairs of the seasons before, against the app's
line, its empirical ranges and its logistic P(top third).

    python bayes_translation.py     # writes BAYES_REPORT.md
"""
import os
import pickle
import sys

import numpy as np
import pandas as pd

import frozen_2026 as fz
import sp_schema as sp

BASE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.join(BASE, "BAYES_REPORT.md")
CACHE = os.environ.get("POST2026_CACHE")
N_ITER, BURN, NU, SEED = 3000, 1000, 6, 0


def gibbs(train, rng):
    m = train.class_source.mean()
    dirs = sorted(train.pair.unique())
    data = {d: (train.class_source[train.pair == d].values - m,
                train.class_target[train.pair == d].values) for d in dirs}
    s2_0 = float(np.var(train.class_target - np.polyval(
        np.polyfit(train.class_source, train.class_target, 1), train.class_source)))
    A, B = float(train.class_target.mean()), 0.3
    ta2, tb2 = 25.0, 0.01
    ab = {d: np.array([A, B]) for d in dirs}
    s2 = {d: s2_0 for d in dirs}
    keep = []
    for it in range(N_ITER):
        for d in dirs:
            x, y = data[d]
            X = np.column_stack([np.ones_like(x), x])
            P0 = np.diag([1 / ta2, 1 / tb2])
            Pn = P0 + X.T @ X / s2[d]
            V = np.linalg.inv(Pn)
            mu = V @ (P0 @ np.array([A, B]) + X.T @ y / s2[d])
            ab[d] = rng.multivariate_normal(mu, V)
            r = y - X @ ab[d]
            s2[d] = 1 / rng.gamma((NU + len(y)) / 2, 2 / (NU * s2_0 + r @ r))
        a = np.array([ab[d][0] for d in dirs])
        b = np.array([ab[d][1] for d in dirs])
        A = rng.normal(a.mean(), np.sqrt(ta2 / len(dirs)))
        B = rng.normal(b.mean(), np.sqrt(tb2 / len(dirs)))
        ta2 = 1 / rng.gamma(1 + len(dirs) / 2, 1 / (1 + ((a - A) ** 2).sum() / 2))
        tb2 = 1 / rng.gamma(1 + len(dirs) / 2, 1 / (1 + ((b - B) ** 2).sum() / 2))
        if it >= BURN and it % 2 == 0:
            keep.append(({d: ab[d].copy() for d in dirs}, dict(s2), A, B, ta2, tb2))
    return keep, m


def predictive(keep, m, rows, rng):
    """Draws of y for each row: one per kept iteration."""
    out = np.empty((len(rows), len(keep)))
    for j, (ab, s2, A, B, ta2, tb2) in enumerate(keep):
        for i, r in enumerate(rows.itertuples()):
            if r.pair in ab:
                a, b, s = ab[r.pair][0], ab[r.pair][1], s2[r.pair]
            else:
                a, b = rng.normal(A, np.sqrt(ta2)), rng.normal(B, np.sqrt(tb2))
                s = np.mean(list(s2.values()))
            out[i, j] = a + b * (r.class_source - m) + rng.normal(0, np.sqrt(s))
    return np.clip(out, 0, 100)


def run():
    D = pickle.load(open(CACHE, "rb"))
    e = pd.read_csv(os.path.join(BASE, "post2026_explore", "entrants.csv"))
    e["player_id"] = sp.normalize_player_id(e.player_id.astype(str))
    thr = {}
    for t, sea in D["sea_at"].items():
        s = sea[sea.n_games >= 3]
        thr[t] = s.groupby(["comp", "season"]).class_score.quantile(2 / 3).to_dict()
    rng = np.random.default_rng(SEED)
    res = []
    for t in (2023, 2024, 2025, 2026):
        tr = D["pairs"][t].copy()
        tr["pair"] = tr.source + "->" + tr.target
        keep, m = gibbs(tr, rng)
        ev = e[e.season_tgt == t].copy()
        draws = predictive(keep, m, ev, rng)
        ev["bayes_mean"] = draws.mean(1)
        for q in (10, 25, 75, 90):
            ev[f"b{q}"] = np.percentile(draws, q, axis=1)
        last = {c: thr[t - 1].get((c, t - 1), np.nan) for c in ev.target.unique()}
        tt = ev.target.map(last).values
        ev["p_top3_bayes"] = (draws >= tt[:, None]).mean(1)
        res.append(ev)
    return pd.concat(res, ignore_index=True)


def report(R):
    L = ["# Hierarchical Bayesian translation", "",
         "Generated by `bayes_translation.py`; model in its docstring. Rolling, landing "
         "seasons 2023–2026.", "",
         "| Entrants | n | MAE, app line | MAE, posterior mean | Δ [95%] | 50% range: app / "
         "Bayes | 80% range: app / Bayes | Brier P(top third): app / Bayes |",
         "|---|---|---|---|---|---|---|---|"]
    for lab, g in (("into SL from NRL/NSW/QLD", R[R.pair.isin({"NRL->SL", "NSW->SL",
                                                               "QLD->SL"})]),
                   ("all directions", R)):
        y = g.class_target
        d, lo, hi = fz.paired_bootstrap(y.values, g.S0.values, g.bayes_mean.values,
                                        g.player_id.values)
        app50 = ((y >= (g.S0 + g.e25).clip(0, 100)) & (y <= (g.S0 + g.e75).clip(0, 100))).mean()
        app80 = ((y >= (g.S0 + g.e10).clip(0, 100)) & (y <= (g.S0 + g.e90).clip(0, 100))).mean()
        b50 = ((y >= g.b25) & (y <= g.b75)).mean()
        b80 = ((y >= g.b10) & (y <= g.b90)).mean()
        br_app = np.mean((g.p_top3_S0 - g.top3) ** 2)
        br_b = np.mean((g.p_top3_bayes - g.top3) ** 2)
        L.append(f"| {lab} | {len(g)} | {np.abs(y - g.S0).mean():.2f} | "
                 f"{np.abs(y - g.bayes_mean).mean():.2f} | {d:+.2f} [{lo:+.2f}, {hi:+.2f}] | "
                 f"{app50:.0%} / {b50:.0%} | {app80:.0%} / {b80:.0%} | "
                 f"{br_app:.3f} / {br_b:.3f} |")
    L += ["", "Δ > 0 means the posterior mean is closer. The app's P(top third) is the "
          "logistic calibration of the exploration (`explore_post2026.py`).", ""]
    open(REPORT, "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    report(run())
    sys.exit(0)
