"""Team strength read from the betting market, and the weather.

C3, market ratings. Every handicap is the market's view of the gap between two teams.
Fitting team ratings to the lines of the weeks before a match (ridge, this season's
earlier rounds and last season's at half weight, with a home term) gives a team-
strength rating built from the market's information rather than from results. Two
questions: is it a better baseline than result ELO for the match model, and does the
player layer still add anything on top of it? Walk-forward by season, on the same
fixtures as `gigot_sl_named.py`.

C4, weather. From Mike's sheets: dry, damp, wet. Does the total line account for wet
weather (actual total minus total line by weather)? Do favourites cover less in the
wet? Do players make more errors per 80 minutes?

    python market_weather.py     # writes MARKET_WEATHER_REPORT.md
"""
import os
import sqlite3
import sys

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge

import gigot_sl_named as gs
import gigot_v2 as gv

BASE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.join(BASE, "MARKET_WEATHER_REPORT.md")
N_BOOT, SEED = 2000, 0


def market_ratings(lines):
    """Pre-match market rating difference for every club-match row."""
    one = lines[lines.team < lines.opposition].dropna(subset=["handicap"]).copy()
    one["home_ind"] = one.venue.map({"home": 1.0, "away": -1.0}).fillna(0.0)
    one["mkt"] = -one.handicap
    teams = sorted(set(lines.team) | set(lines.opposition))
    ix = {t: i for i, t in enumerate(teams)}
    out = {}
    for s in sorted(one.season.unique()):
        for r in sorted(lines[lines.season == s]["round"].unique()):
            past = one[((one.season == s) & (one["round"] < r)) | (one.season == s - 1)]
            if len(past) < 10:
                continue
            X = np.zeros((len(past), len(teams) + 1))
            for k, (a, b, h) in enumerate(zip(past.team, past.opposition, past.home_ind)):
                X[k, ix[a]], X[k, ix[b]], X[k, -1] = 1, -1, h
            w = np.where(past.season == s, 1.0, 0.5)
            m = Ridge(alpha=1.0, fit_intercept=False).fit(X, past.mkt, sample_weight=w)
            rt = dict(zip(teams, m.coef_[:-1]))
            for row in lines[(lines.season == s) & (lines["round"] == r)].itertuples():
                out[(s, r, row.team)] = rt.get(row.team, 0.0) - rt.get(row.opposition, 0.0)
    return out


def boot_mean(x, n=N_BOOT):
    x = np.asarray(x, float)
    x = x[np.isfinite(x)]
    rng = np.random.default_rng(SEED)
    s = [rng.choice(x, len(x)).mean() for _ in range(n)]
    return x.mean(), np.percentile(s, 2.5), np.percentile(s, 97.5), len(x)


def run():
    con = sqlite3.connect(f"file:{gv.DB}?mode=ro", uri=True)
    d = gs.fixtures(con)
    lines = pd.read_sql("SELECT * FROM sl_match_lines", con)
    pm = pd.read_sql("SELECT season, round, team, minutes, errors FROM player_match_stats "
                     "WHERE competition='SL'", con)
    con.close()
    mr = market_ratings(lines)
    d["mkt_rating"] = [mr.get((s, r, t), np.nan) for s, r, t in zip(d.Season, d.Round, d.team_a)]
    feats21 = ["named21_d_class", "named21_d_form", "named21_d_green"]
    d = d.dropna(subset=gs.BASE_F + feats21 + ["mkt_rating"]).reset_index(drop=True)
    d["p_elo"] = gs.walk_forward(d, gs.BASE_F)
    d["p_mkt"] = gs.walk_forward(d, ["mkt_rating", "home"])
    d["p_mkt21"] = gs.walk_forward(d, ["mkt_rating", "home"] + feats21)
    d["p_elo21"] = gs.walk_forward(d, gs.BASE_F + feats21)
    return d, lines, pm


def report(d, lines, pm):
    o = d[d.p_elo.notna() & d.p_mkt.notna()]
    L = ["# Market ratings and the weather", "",
         "Generated by `market_weather.py`; methods in its docstring.", "",
         "## C3. A team rating from the market's earlier lines", "",
         f"{len(o)} fixtures scored out of sample ({o.Season.min()}–{o.Season.max()}).", "",
         "| Model | MAE | Covers against this week's line, when it disagrees |",
         "|---|---|---|"]
    m = o.market.notna()
    for col, lab in (("p_elo", "ELO + home"), ("p_elo21", "ELO + home + named 21"),
                     ("p_mkt", "market rating + home"),
                     ("p_mkt21", "market rating + home + named 21")):
        e = np.abs(o.Margin - o[col]).mean()
        w, n = gs.ats(o.Margin[m].values, o.market[m].values, o[col][m].values)
        L.append(f"| {lab} | {e:.2f} | {100 * w.mean():.1f}% of {n} |")
    L.append(f"| this week's line itself | {np.abs(o.Margin - o.market)[m].mean():.2f} | — |")
    gain = (np.abs(o.Margin - o.p_mkt) - np.abs(o.Margin - o.p_mkt21)).values
    g = boot_mean(gain)
    L += ["", f"Player layer on top of the market rating: MAE gain {g[0]:+.2f} "
          f"[{g[1]:+.2f}, {g[2]:+.2f}].", ""]

    one = lines[lines.team < lines.opposition].dropna(subset=["score_for", "score_against"])
    one = one.assign(total=one.score_for + one.score_against)
    L += ["## C4. Weather", "", "| Weather | Matches | Total minus total line [95%] | "
          "Favourite covers |", "|---|---|---|---|"]
    fav = lines.dropna(subset=["handicap", "score_for"])
    fav = fav[fav.handicap < 0]
    fav = fav.assign(res=fav.score_for - fav.score_against + fav.handicap)
    fav = fav[fav.res != 0]
    one = one[one.total_line.notna()].assign(r=lambda d: d.total - d.total_line)
    one["r_season"] = one.r - one.groupby("season").r.transform("mean")
    for w in ("dry", "damp", "wet"):
        x = one[one.weather == w]
        b = boot_mean(x.r)
        f = fav[fav.weather == w]
        L.append(f"| {w} | {len(x)} | {b[0]:+.1f} [{b[1]:+.1f}, {b[2]:+.1f}] | "
                 f"{(f.res > 0).mean():.0%} of {len(f)} |")
    L += ["", "The same with each season's own average taken out (the line ran 1.6-2.5 "
          "points high in 2021-23 and about right in 2024-26, and damp and wet matches "
          "cluster in 2023):", "", "| Weather | Total minus line, season-demeaned [95%] | "
          "2024-26 only [95%] |", "|---|---|---|"]
    for w in ("dry", "damp", "wet"):
        x = one[one.weather == w]
        b = boot_mean(x.r_season)
        c = boot_mean(x[x.season >= 2024].r)
        L.append(f"| {w} | {b[0]:+.1f} [{b[1]:+.1f}, {b[2]:+.1f}] | "
                 f"{c[0]:+.1f} [{c[1]:+.1f}, {c[2]:+.1f}] ({c[3]}) |")
    j = pm.merge(lines[["season", "round", "team", "weather"]], on=["season", "round", "team"])
    L += ["", "Errors per 80 minutes, every Super League player-match:", "",
          "| Weather | Player-matches | Errors per 80 |", "|---|---|---|"]
    for w in ("dry", "damp", "wet"):
        x = j[j.weather == w]
        L.append(f"| {w} | {len(x):,} | {80 * x.errors.sum() / x.minutes.sum():.2f} |")
    L.append("")
    open(REPORT, "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    report(*run())
    sys.exit(0)
