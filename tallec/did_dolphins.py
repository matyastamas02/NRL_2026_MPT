# -*- coding: utf-8 -*-
"""Staggered difference-in-differences for moves, and the Dolphins' entry as a natural
experiment.

A2. Players move in different seasons, and a two-way fixed-effects regression over
such staggered moves mixes early movers in as controls for late ones (Goodman-Bacon;
Callaway and Sant'Anna 2021). The clean version estimates one effect per cohort
(direction x landing season) and event time e, against controls who have not moved:
    ATT(g, e) = mean over movers of [y(t+e) - y(t-1)]
                - the same change predicted for them from the stayers of that source
                  competition and season (regression of the change on the season-before
                  profile, fitted on stayers still in the source competition at t+e)
and aggregates the cohorts with their numbers of movers. e = 0, 1, 2 are the first
three seasons after the move; e = -2 (y(t-2) - y(t-1), sign flipped) is the pre-trend
placebo. Unlike the matching, it differences out each mover's own level.

A5. The Dolphins entered the NRL in 2023, a new club needing a squad at once. Cup
players promoted to it were promoted because a team had to be filled, more than
because they had been picked out, so their shift is closer to a promotion without
selection on unobservables. Compared with every other Cup-to-NRL promotion, matched
the same way (`matching_moves.py`).

    python did_dolphins.py      # writes DID_DOLPHINS_REPORT.md
"""
import os
import sqlite3
import sys

import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression

import matching_moves as mm
import rolling_backtest as rb
import sp_schema as sp

BASE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.join(BASE, "DID_DOLPHINS_REPORT.md")
X_COLS = ["y_prev", "cls", "age", "mins_pg", "games", "start_share"]


def did(D, M, S):
    sea = D["sea"].set_index(["player_id", "comp", "season"]).class_score
    get = lambda p, c, y: sea.get((p, c, int(y)), np.nan)
    rows = []
    for e in (-2, 0, 1, 2):
        for (src, tgt, t), g in M.groupby(["source", "target", "season_tgt"]):
            yr = t + e
            comp_m = src if e < 0 else tgt
            ym = np.array([get(p, comp_m, yr) for p in g.player_id])
            if e == -2:
                ym = np.array([get(p, src, yr) for p in g.player_id])
            dm = (ym - g.y_prev.values) * (-1 if e == -2 else 1)
            st = S[(S.comp == src) & (S.season_src == t - 1)].copy()
            ys = np.array([get(p, src, yr) for p in st.player_id])
            ds = (ys - st.y_prev.values) * (-1 if e == -2 else 1)
            ok = np.isfinite(ds)
            okm = np.isfinite(dm)
            if ok.sum() < 30 or okm.sum() == 0:
                continue
            Xs = st[X_COLS].astype(float).fillna(st[X_COLS].median()).values
            Xm = g[X_COLS].astype(float).fillna(st[X_COLS].median()).values
            pred = LinearRegression().fit(Xs[ok], ds[ok]).predict(Xm)
            att = dm - pred
            for p, a in zip(g.player_id.values[okm], att[okm]):
                rows.append(dict(source=src, target=tgt, season_tgt=t, e=e,
                                 player_id=p, att=a))
    return pd.DataFrame(rows)


def boot(x, ids, n=2000, seed=0):
    x, ids = np.asarray(x, float), np.asarray(ids)
    u = np.array(sorted(pd.unique(ids)))
    at = {p: np.flatnonzero(ids == p) for p in u}
    rng = np.random.default_rng(seed)
    s = [x[np.concatenate([at[p] for p in rng.choice(u, u.size)])].mean() for _ in range(n)]
    return float(x.mean()), float(np.percentile(s, 2.5)), float(np.percentile(s, 97.5))


def dolphins(con, Mm):
    ps = pd.read_sql("SELECT player_id, comp, season, team FROM player_season_starts "
                     "WHERE comp='NRL' AND season=2023", con)
    ps["player_id"] = sp.normalize_player_id(ps.player_id)
    dol = set(ps[ps.team.str.startswith("Dolphins")].player_id)
    up = Mm[(Mm.target == "NRL") & Mm.source.isin(["NSW", "QLD"])].copy()
    up["dolphins"] = up.player_id.isin(dol) & (up.season_tgt == 2023)
    return up


def run():
    con = sqlite3.connect(f"file:{rb.DB}?mode=ro", uri=True)
    D = mm.load(con)
    M = mm.movers(D)
    S = mm.stayers(D, M)
    A = did(D, M, S)
    _, Mm, _, _, _ = mm.run(D=D)
    up = dolphins(con, Mm)
    con.close()
    return A, up


def report(A, up):
    L = ["# Staggered DiD for moves, and the Dolphins' entry", "",
         "Generated by `did_dolphins.py`; methods in its docstring. Season-only peer "
         "scores, 3+ matches. Intervals: 95% player-cluster bootstrap.", "",
         "## A2. Effect by event time", "",
         "Change in a mover's rating from the season before the move, minus the change "
         "comparable stayers made over the same seasons. e = −2 is the placebo (should be "
         "about 0).", "",
         "| Moves | e | Movers | ATT [95%] |", "|---|---|---|---|"]
    groups = {"into SL from NRL/NSW/QLD": A.target.eq("SL") & A.source.isin(["NRL", "NSW", "QLD"]),
              "NRL -> NSW Cup": (A.source == "NRL") & (A.target == "NSW"),
              "NSW Cup -> NRL": (A.source == "NSW") & (A.target == "NRL"),
              "NRL -> QLD Cup": (A.source == "NRL") & (A.target == "QLD"),
              "QLD Cup -> NRL": (A.source == "QLD") & (A.target == "NRL")}
    for lab, m in groups.items():
        for e, g in A[m].groupby("e"):
            if len(g) < 8:
                continue
            b = boot(g.att, g.player_id)
            L.append(f"| {lab} | {e:+d} | {len(g)} | {b[0]:+.1f} [{b[1]:+.1f}, {b[2]:+.1f}] |")
    sl = A[groups["into SL from NRL/NSW/QLD"]]
    w = sl.pivot_table(index=["player_id", "season_tgt"], columns="e", values="att")
    if 0 in w and 1 in w:
        both = w.dropna(subset=[0, 1])
        b = boot(both[1] - both[0], both.index.get_level_values(0))
        L += ["", f"Into SL, same movers in seasons one and two ({len(both)}): change from "
              f"e = 0 to e = 1, {b[0]:+.1f} [{b[1]:+.1f}, {b[2]:+.1f}]."]
    L += ["", "## A5. Cup players promoted to the Dolphins in 2023", "",
          "Matched shift (rating in the NRL minus matched Cup stayers' rating), "
          "`matching_moves.py`.", "", "| Promotions | Movers | Matched shift [95%] |",
          "|---|---|---|"]
    for v, g in up.groupby("dolphins"):
        b = boot(g.att_i, g.player_id)
        L.append(f"| {'to the Dolphins, 2023' if v else 'every other Cup-to-NRL promotion'} "
                 f"| {len(g)} | {b[0]:+.1f} [{b[1]:+.1f}, {b[2]:+.1f}] |")
    L += ["", "A more negative shift for the Dolphins' promotions would mean ordinary "
          "promotions are selected on something the data do not see.", ""]
    open(REPORT, "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    report(*run())
    sys.exit(0)
