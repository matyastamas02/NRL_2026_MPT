# -*- coding: utf-8 -*-
"""Conformal forecast ranges against the empirical ones the app shows.

The app's 50% and 80% ranges are quantiles of the line's errors on its own training
pairs (predict_translation.RANGE_Q). Split conformal prediction uses errors the
forecast made out of sample instead: for landing season t, the residuals of the
entrants of the seasons before t, scored when they were forecast. With n calibration
residuals the range is the forecast plus the ceil((n+1)(1-a))/n quantile of their
absolute size, which guarantees coverage of at least 1-a whenever the new entrants are
exchangeable with the old ones. Two refinements:
  normalised   residuals divided by the line's own residual SD, so a direction with a
               noisier line gets a wider range (conditional coverage across directions)
  Mondrian     calibrated separately for entrants into Super League and the rest
Only the seasons with an out-of-sample calibration set are scored: 2024 (calibrated on
2023), 2025 (2023-24) and 2026 (2023-25). Input: post2026_explore/entrants.csv.

    python conformal_ranges.py      # writes CONFORMAL_REPORT.md
"""
import math
import os
import sys

import numpy as np
import pandas as pd

BASE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.join(BASE, "CONFORMAL_REPORT.md")
LEVELS = (0.5, 0.8)


def qhat(scores, a):
    n = len(scores)
    k = min(n, math.ceil((n + 1) * (1 - a)))
    return float(np.sort(scores)[k - 1])


def run():
    e = pd.read_csv(os.path.join(BASE, "post2026_explore", "entrants.csv"))
    e["resid"] = e.class_target - e.S0
    e["group"] = np.where(e.target == "SL", "into SL", "other")
    rows = []
    for t in (2024, 2025, 2026):
        cal, te = e[e.season_tgt < t], e[e.season_tgt == t].copy()
        for lev in LEVELS:
            a = 1 - lev
            for name, score, scale, by_group in (
                    ("split", np.abs(cal.resid), None, False),
                    ("normalised", np.abs(cal.resid) / cal.sd, "sd", False),
                    ("Mondrian, normalised", np.abs(cal.resid) / cal.sd, "sd", True)):
                if by_group:
                    w = np.zeros(len(te))
                    for g in te.group.unique():
                        q = qhat(score[cal.group == g].values, a)
                        w[(te.group == g).values] = q * te.sd[te.group == g].values
                else:
                    q = qhat(score.values, a)
                    w = q * (te[scale].values if scale else np.ones(len(te)))
                lo, hi = (te.S0 - w).clip(0, 100), (te.S0 + w).clip(0, 100)
                cov = (te.class_target >= lo) & (te.class_target <= hi)
                for g, m in (("into SL", te.group == "into SL"), ("all", te.index == te.index)):
                    rows.append(dict(season=t, level=lev, method=name, entrants=g,
                                     n=int(m.sum()), covered=cov[m].sum(),
                                     width=float((hi - lo)[m].mean())))
            # the app's empirical range for comparison
            ql, qh = ((te.e25, te.e75) if lev == 0.5 else (te.e10, te.e90))
            lo, hi = (te.S0 + ql).clip(0, 100), (te.S0 + qh).clip(0, 100)
            cov = (te.class_target >= lo) & (te.class_target <= hi)
            for g, m in (("into SL", te.group == "into SL"), ("all", te.index == te.index)):
                rows.append(dict(season=t, level=lev, method="app (training-pair quantiles)",
                                 entrants=g, n=int(m.sum()), covered=cov[m].sum(),
                                 width=float((hi - lo)[m].mean())))
    return pd.DataFrame(rows)


def report(R):
    agg = (R.groupby(["entrants", "level", "method"])
             .apply(lambda g: pd.Series({"n": g.n.sum(), "coverage": g.covered.sum() / g.n.sum(),
                                         "width": np.average(g.width, weights=g.n)}),
                    include_groups=False).reset_index())
    L = ["# Conformal ranges against the app's", "",
         "Generated by `conformal_ranges.py`. Landing seasons 2024–2026, each calibrated on "
         "the out-of-sample errors of the seasons before it.", "",
         "| Entrants | Nominal | Method | Entrants scored | Covered | Mean width |",
         "|---|---|---|---|---|---|"]
    for r in agg.sort_values(["entrants", "level", "method"]).itertuples():
        L.append(f"| {r.entrants} | {r.level:.0%} | {r.method} | {int(r.n)} | "
                 f"{r.coverage:.0%} | {r.width:.1f} |")
    by = (R[R.entrants == "into SL"].groupby(["season", "level", "method"])
            .apply(lambda g: g.covered.sum() / g.n.sum(), include_groups=False)
            .unstack("season"))
    L += ["", "Coverage into Super League by season:", "", "```", by.round(2).to_string(),
          "```", ""]
    open(REPORT, "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    report(run())
    sys.exit(0)
